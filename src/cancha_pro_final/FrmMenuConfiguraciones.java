    public void cargarTablaArchivos(boolean mostrarAviso) {
        modeloTabla.setRowCount(0);
        String[] resultados = Configuraciones.verificarArchivos(archivosSistema);

        for (int i = 0; i < archivosSistema.length; i++) {
            modeloTabla.addRow(new Object[]{
                archivosSistema[i],
                resultados[i]
            });
        }

        if (mostrarAviso) {
            JOptionPane.showMessageDialog(this, "Archivos verificados y cargados correctamente.");
        }
    }
   

