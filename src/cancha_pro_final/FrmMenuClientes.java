   public void cargartablaclientes (){
      DefaultTableModel modelo =  (DefaultTableModel) TableClientes.getModel();
      modelo.setRowCount(0);
        
      try {
    FileReader leerclientes = new FileReader("Clientes.txt");
    BufferedReader buffcli = new BufferedReader(leerclientes);

    String temporal;
    while ((temporal = buffcli.readLine()) != null) {
        if (temporal.trim().isEmpty()) continue;

        String[] datoslinea = temporal.split(",", -1);

        String codigo    = (datoslinea.length > 0) ? datoslinea[0] : "";
        String nombre    = (datoslinea.length > 1) ? datoslinea[1] : "";
        String correo    = (datoslinea.length > 2) ? datoslinea[2] : "";
        String telefono  = (datoslinea.length > 3) ? datoslinea[3] : "";
        String frecuente = (datoslinea.length > 4) ? datoslinea[4] : "";

        String fecha;
        if (datoslinea.length > 5 && !datoslinea[5].trim().isEmpty()) {
            fecha = datoslinea[5];
        } else {
            fecha = "04/11/2026";
        }

        Object[] filaCompleta = new Object[]{codigo, nombre, correo, telefono, frecuente, fecha};
        modelo.addRow(filaCompleta);
        }

    buffcli.close();
    leerclientes.close();

       } catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error al cargar: " + e.getMessage());
}
       
       generarcodigo();
       actualizarbarras();
    }
   
   
   public void generarcodigo (){      
       int fila = TableClientes.getRowCount();
       int aux  = fila +1;

       String codigo= "";
       
       if (aux<10){
           codigo = "C00"+aux;
       }else if (aux <100){
           codigo = "C0"+aux;
       }else {
           codigo = "C"+aux;
       }
       Txcodigo.setText(codigo);
       Txcodigo.setEnabled(false);
         Clientes cli = new Clientes();
         String nuevoCodigo = cli.generarSiguienteCodigo(TableClientes);
        Txcodigo.setText(nuevoCodigo);
 }
   
   private void actualizarbarras(){
       int total  = TableClientes.getRowCount();
       int frecue = 0;
       
       for (int i = 0; i<total; i++){
            String texto =TableClientes.getValueAt(i, 4).toString().trim();
            if(texto.equalsIgnoreCase("Si")){
                frecue = frecue+1;
            }
       }
      lbTotalClientes.setText("Total Clientes : "+total);
      lbTotalRegistro.setText("Clientes Frecuentes: " + frecue);
      barfrecuencia.setStringPainted(true);
      if(total>0){
          int porcentaje =(frecue*100)/total;
          barfrecuencia.setValue(porcentaje);
          barfrecuencia.setString(porcentaje+"% Frecuentes");
      }else{
      barfrecuencia.setValue(0);
      barfrecuencia.setString ("0% Frecuentes");
      }
   }
   
